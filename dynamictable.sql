CREATE OR REPLACE DYNAMIC TABLE DT_ORDER1 
WAREHOUSE ='COMPUTE_WH'
TARGET_LAG ='1 Minute'
INITIALIZE =ON_SCHEDULE 
REFRESH_MODE =AUTO 
AS
SELECT
    order_id,
    customer_id,
    order_date,
    quantity,
    unit_price,
    ORDER_STATUS.
    quantity * unit_price AS order_amount
FROM RAW_ORDERS
WHERE order_status IS NOT NULL;

Select * from DT_ORDER1;



